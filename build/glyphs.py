D='dl'
curated = [0xE0B0,0xE0B1,0xE0B2,0xE0B3,0xE0B4,0xE0B5,0xE0B6,0xE0B7,0xE0B8,0xE0B9,0xE0BA,0xE0BB,0xE0BC,0xE0BD,0xE0BE,0xE0BF,0xE0C0,0xE0C1,0xE0C2,0xE0C3,0xE0C4,0xE0C5,0xE0C6,0xE0C7,0xE0C8,0xE0CA,0xE0CC,0xE0CD,0xE0CE,0xE0CF,0xE0D0,0xE0D1,0xE0D2,0xE0D4,0xE0A0,0xE0A1,0xE0A2,
 0xF015,0xF07B,0xF07C,0xF023,0xF017,0xF120,0xF09B,0xF1D3,0xE702,0xF418,0xF126,0xF00C,0xF00D,0xF071,0xF0E7,0xF004,0xF005,0xF135,0xF013,0xF007,0xF233,0xF0C2,0xF054,0xF105,0xF101,0xF17C,0xF179,0xF17A,0xF303,0xF31A,0xF308,0xF489,0xF111,0xF10C,0xF0F3,0xF1B2,0xF0AD,0xF06D,0xF186,0xF185,0xF0A3,0xF02A2,0xF0241,0xF024B,0xF0954,0xF0C9C,0xF02B,0xF292,0xF0E8, 0xF4A5,0xF0EB,0xE7A8,0xE718,0xE73C,0xE627,0xE65E,0xE738,0xE7C5,0xF1EB,0xF2DB,0xF0AC]
chars=set(curated)
for f in ['nf.toml','pastel.toml','tokyo.toml','gruvbox.toml','schema.json']:
    for ch in open(f'{D}/{f}',encoding='utf-8').read():
        c=ord(ch)
        if 0xE000<=c<=0xF8FF or c>=0xF0000: chars.add(c)
u=','.join('U+%04X'%c for c in sorted(chars))
subprocess.run(['pyftsubset',f'{D}/sym/SymbolsNerdFont-Regular.ttf','--unicodes='+u,'--flavor=woff2','--output-file=build/nfsub.woff2','--no-layout-closure'],check=True)
b=open('build/nfsub.woff2','rb').read()
print(len(chars),'glyphs',len(b),'bytes')
open('build/nfsub.b64','w').write(base64.b64encode(b).decode())
json.dump([chr(c) for c in curated],open('build/curated.json','w'),ensure_ascii=False)
